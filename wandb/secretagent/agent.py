class Job(object):

    def __init__(self, command):
        job_type = command.get("type")
        self.type = job_type
        if job_type == "run":
            self.run_id = command.get("run_id")
            self.config = config = command.get("args")

    def __repr__(self):
        return "Job({},{})".format(self.run_id, self.config)

    def done(self):
        return self.type == "exit"


class Agent(object):

    def __init__(self, sweep_id, project=None, entity=None, function=None, count=None):
        self._sweep_id = sweep_id
        self._project = project
        self._entity = entity
        self._function = function
        self._count = count
        # glob_config = os.path.expanduser('~/.config/wandb/settings')
        # loc_config = 'wandb/settings'
        # files = (glob_config, loc_config)
        settings = Settings()
        self._api = InternalApi()
        self._settings = settings
        self._agent_id = None

    def register(self):
        agent = self._api.register_agent(
            socket.gethostname(), sweep_id=self._sweep_id)
        self._agent_id = agent['id']

    def check_queue(self):
        run_status = dict()
        commands = self._api.agent_heartbeat(self._agent_id, {}, run_status)
        print("got", commands)
        if not commands:
            return
        command = commands[0]
        job = Job(command)
        return job

    def run_job(self, job):
        print("agent: got job", job)

        sweep_id = self._sweep_id
        run_id = job.run_id

        config_file = os.path.join("wandb", "sweep-" + sweep_id, "config-" + run_id + ".yaml")
        config_util.save_config_file_from_dict(config_file, job.config)
        os.environ[wandb.env.RUN_ID] = run_id
        os.environ[wandb.env.CONFIG_PATHS] = config_file

        try:
            self._function()
            wandb.join()
        except KeyboardInterrupt as e:
            print("keyb", e)
        except Exception as e:
            print("problem", e)

    def loop(self):
        self.register()
        os.environ[wandb.env.SWEEP_ID] = self._sweep_id
        #wandb.setup(settings=wandb.Settings(sweep_id=self._sweep_id))
        #print("GOT ENV", os.environ)
        while True:
            job = self.check_queue()
            if not job:
                time.sleep(20)
                continue
            if job.done():
                break
            self.run_job(job)
            time.sleep(5)


def agent(sweep_id, function=None, entity=None, project=None, count=None):
    """Generic agent entrypoint, used for CLI or jupyter.

    Args:
        sweep_id (dict): Sweep ID generated by CLI or sweep API
        function (func, optional): A function to call instead of the "program" specifed in the config
        entity (str, optional): W&B Entity
        project (str, optional): W&B Project
        count (int, optional): the number of trials to run.
    """
    if function is None:
        raise Exception("function paramter is required")
    if not callable(function):
        raise Exception("function paramter must be callable")
    agent = Agent(sweep_id, function=function, entity=entity, project=project, count=count)
    agent.loop()
